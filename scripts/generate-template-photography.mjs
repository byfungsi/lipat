import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Runtime assets remain self-contained in the optional /templates entrypoint.
const directory = new URL("../packages/templates/assets/", import.meta.url);
const photos = Object.fromEntries(
  readdirSync(directory)
    .filter((name) => name.endsWith(".jpg"))
    .sort()
    .map((name) => [
      name.slice(0, -4),
      readFileSync(new URL(name, directory)).toString("base64"),
    ]),
);
const output = `// Generated by scripts/generate-template-photography.mjs. Do not edit by hand.
import type { DeckAsset } from "@lipat-internal/model";
import type { TemplatePhotoKey } from "./template-art-direction";

const photos: Readonly<Record<TemplatePhotoKey, string>> = ${JSON.stringify(photos, null, 2)};

/** Return a fresh, embedded photograph; no fetch, DOM or engine is required. */
export function createTemplatePhoto(key: TemplatePhotoKey): DeckAsset {
  return { id: \`template-photo-\${key}\`, mimeType: "image/jpeg", data: photos[key] };
}
`;
const target = new URL(
  "../packages/templates/src/template-photography.generated.ts",
  import.meta.url,
);
writeFileSync(target, output);
console.log(
  `Embedded ${Object.keys(photos).length} photographs in ${fileURLToPath(target)}`,
);
